async function findModerationState(submissionId) {
  return withConnection(async (connection) => {
    const submissionResult = await connection.execute(
      `
        SELECT
          submission_status AS "submissionStatus",
          approved_at AS "approvedAt"
        FROM submissions
        WHERE submission_id = :submissionId
      `,
      { submissionId }
    );
    const actionResult = await connection.execute(
      `
        SELECT
          action_id AS "actionId",
          action_type AS "actionType",
          previous_status AS "previousStatus",
          new_status AS "newStatus",
          action_note AS "actionNote"
        FROM moderation_actions
        WHERE submission_id = :submissionId
        ORDER BY action_at, action_id
      `,
      { submissionId }
    );

    return {
      submission: submissionResult.rows[0] || null,
      actions: actionResult.rows
    };
  });
}

async function countVerifiedContributions(companyId) {
  return withConnection(async (connection) => {
    const result = await connection.execute(
      `
        SELECT NVL(SUM(contribution_count), 0) AS "contributionCount"
        FROM vw_verified_salary_summary
        WHERE company_id = :companyId
      `,
      { companyId }
    );

    return result.rows[0].contributionCount;
  });
}

async function findInternalUserByEmail(email) {
  return withConnection(async (connection) => {
    const result = await connection.execute(
      `
        SELECT
          u.user_id AS "userId",
          u.password_hash AS "passwordHash",
          u.user_type AS "userType",
          u.account_role AS "accountRole",
          u.account_status AS "accountStatus",
          e.employee_id AS "employeeId",
          e.employment_status AS "employmentStatus"
        FROM users u
        LEFT JOIN employees e ON e.user_id = u.user_id
        WHERE u.email = :email
      `,
      { email }
    );

    return result.rows[0] || null;
  });
}

async function findSalaryPair(submissionId) {
  return withConnection(async (connection) => {
    const result = await connection.execute(
      `
        SELECT
          s.submission_id AS "parentSubmissionId",
          ss.submission_id AS "childSubmissionId",
          s.submission_status AS "submissionStatus",
          s.verification_status AS "verificationStatus",
          s.approved_at AS "approvedAt",
          ss.role_id AS "roleId",
          ss.base_salary AS "baseSalary"
        FROM submissions s
        JOIN salary_submissions ss ON ss.submission_id = s.submission_id
        WHERE s.submission_id = :submissionId
      `,
      { submissionId }
    );

    return result.rows[0] || null;
  });
}

