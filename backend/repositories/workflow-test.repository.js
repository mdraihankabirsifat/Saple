async function countSubmissionsForUser(userId) {
  return withConnection(async (connection) => {
    const result = await connection.execute(
      `
        SELECT
          COUNT(*) AS "submissionCount"
        FROM submissions
        WHERE user_id = :userId
      `,
      { userId }
    );

    return result.rows[0].submissionCount;
  });
}

async function cleanupWorkflowUsers(normalEmail, employeeEmail) {
  let connection;

  try {
    connection = await database.getConnection();
    const binds = { normalEmail, employeeEmail };

    await connection.execute(
      `
        DELETE FROM submissions
        WHERE user_id IN (
          SELECT user_id
          FROM users
          WHERE email IN (:normalEmail, :employeeEmail)
        )
      `,
      binds
    );
    await connection.execute(
      `
        DELETE FROM users
        WHERE email IN (:normalEmail, :employeeEmail)
      `,
      binds
    );
    await connection.commit();
  } catch (error) {
    if (connection) {
      await connection.rollback();
    }
    throw error;
  } finally {
    if (connection) {
      await connection.close();
    }
  }
}

