-- 9. Public and analytical views
-- These views intentionally omit account data, private verification details,
-- reporter identity, rejection reasons, proof references, and internal notes.
-- ================================================================

CREATE OR REPLACE VIEW vw_public_companies AS
SELECT company_id,
       company_name,
       industry,
       headquarters_city,
       country,
       website,
       company_size,
       description
FROM companies;

CREATE OR REPLACE VIEW vw_public_approved_reviews AS
SELECT s.submission_id,
       s.company_id,
       c.company_name,
       r.role_id,
       jr.role_name,
       r.review_title,
       r.overall_rating,
       r.work_life_balance_rating,
       r.career_growth_rating,
       r.management_rating,
       r.culture_rating,
       r.pros,
       r.cons,
       r.advice_to_management,
       r.employment_status,
       r.review_date,
       s.verification_status,
       s.submitted_at
FROM submissions s
JOIN company_reviews r ON r.submission_id = s.submission_id
JOIN companies c ON c.company_id = s.company_id
LEFT JOIN job_roles jr ON jr.role_id = r.role_id
WHERE s.submission_type = 'REVIEW'
  AND s.submission_status = 'APPROVED';

CREATE OR REPLACE VIEW vw_verified_salary_summary AS
SELECT s.company_id,
       c.company_name,
       ss.role_id,
       jr.role_name,
       ss.currency,
       ss.pay_period,
       MIN(ss.base_salary) AS minimum_salary,
       MAX(ss.base_salary) AS maximum_salary,
       ROUND(AVG(ss.base_salary), 2) AS average_salary,
       COUNT(*) AS contribution_count
FROM submissions s
JOIN salary_submissions ss ON ss.submission_id = s.submission_id
JOIN companies c ON c.company_id = s.company_id
JOIN job_roles jr ON jr.role_id = ss.role_id
WHERE s.submission_type = 'SALARY'
  AND s.submission_status = 'APPROVED'
  AND s.verification_status = 'VERIFIED'
GROUP BY s.company_id, c.company_name, ss.role_id, jr.role_name,
         ss.currency, ss.pay_period;

CREATE OR REPLACE VIEW vw_community_salary_summary AS
SELECT s.company_id,
       c.company_name,
       ss.role_id,
       jr.role_name,
       ss.currency,
       ss.pay_period,
       MIN(ss.base_salary) AS minimum_salary,
       MAX(ss.base_salary) AS maximum_salary,
       ROUND(AVG(ss.base_salary), 2) AS average_salary,
       COUNT(*) AS contribution_count
FROM submissions s
JOIN salary_submissions ss ON ss.submission_id = s.submission_id
JOIN companies c ON c.company_id = s.company_id
JOIN job_roles jr ON jr.role_id = ss.role_id
WHERE s.submission_type = 'SALARY'
  AND s.submission_status = 'APPROVED'
GROUP BY s.company_id, c.company_name, ss.role_id, jr.role_name,
         ss.currency, ss.pay_period;

-- ================================================================
-- 10. Important business rules
-- ================================================================
-- The application enforces these cross-table rules:
-- * employees.user_id belongs to a users row whose user_type is EMPLOYEE.
-- * reviewed_by, resolved_by, and moderator_user_id identify ACTIVE ADMIN users.
-- * current employees use COMPANY_EMAIL_OTP and former employees use DOCUMENT.
-- * at most one PENDING verification exists per employee/company at a time;
--   history is retained, so a normal UNIQUE constraint would be too restrictive.
-- * each subtype row matches submissions.submission_type.
-- * submission verification is valid for the submission's specific company.
-- * timestamps and allowed status transitions follow the application workflow.
-- * moderation_actions rows are append-only during normal application operation.
