-- ================================================================
-- 2. Core account tables
-- ================================================================

CREATE TABLE users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name      VARCHAR2(120) NOT NULL,
    email          VARCHAR2(254) NOT NULL,
    -- Sensitive: password_hash must never be returned by public APIs.
    password_hash  VARCHAR2(255) NOT NULL,
    user_type      VARCHAR2(10) DEFAULT 'NORMAL' NOT NULL,
    account_role   VARCHAR2(10) DEFAULT 'USER' NOT NULL,
    account_status VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_full_name CHECK (TRIM(full_name) IS NOT NULL),
    CONSTRAINT ck_users_email CHECK (TRIM(email) IS NOT NULL),
    CONSTRAINT ck_users_password_hash CHECK (LENGTH(password_hash) >= 20),
    CONSTRAINT ck_users_type CHECK (user_type IN ('NORMAL', 'EMPLOYEE')),
    CONSTRAINT ck_users_role CHECK (account_role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'DEACTIVATED'))
);

CREATE TABLE employees (
    employee_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id           NUMBER NOT NULL,
    employment_status VARCHAR2(10) NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (employee_id),
    CONSTRAINT uk_employees_user UNIQUE (user_id),
    CONSTRAINT fk_employees_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_employees_status CHECK (employment_status IN ('CURRENT', 'FORMER'))
);

