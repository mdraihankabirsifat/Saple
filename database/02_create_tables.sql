CREATE TABLE salary_submissions (
    submission_id          NUMBER,
    role_id                NUMBER NOT NULL,
    base_salary            NUMBER(12,2) NOT NULL,
    additional_compensation NUMBER(12,2),
    currency               VARCHAR2(3) DEFAULT 'BDT' NOT NULL,
    pay_period             VARCHAR2(10) NOT NULL,
    years_of_experience    NUMBER(4,1) NOT NULL,
    employment_type        VARCHAR2(15) NOT NULL,
    work_mode              VARCHAR2(10) NOT NULL,
    salary_year            NUMBER(4) NOT NULL,
    CONSTRAINT pk_salary_submissions PRIMARY KEY (submission_id),
    CONSTRAINT fk_salary_submission FOREIGN KEY (submission_id)
