-- NOTIFICATIONS is always private to exactly one account.
CREATE TABLE notifications (
    notification_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT NOT NULL,
    notification_type   VARCHAR(30) NOT NULL,
    title               VARCHAR(160) NOT NULL,
    message             VARCHAR(600) NOT NULL,
    related_entity_type VARCHAR(30),
    related_entity_id   BIGINT,
    read_at             TIMESTAMPTZ,
    created_at          TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_notifications PRIMARY KEY (notification_id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_title CHECK (TRIM(title) <> ''),
    CONSTRAINT ck_notifications_message CHECK (TRIM(message) <> ''),
    CONSTRAINT ck_notifications_type CHECK (notification_type IN (
        'VERIFICATION_DECISION',
        'SUBMISSION_DECISION',
        'REPRESENTATIVE_DECISION',
        'REPORT_OUTCOME',
        'APPLICATION_RECEIVED',
        'APPLICATION_STATUS',
        'JOB_CLOSED',
        'SECURITY_EVENT'
    )),
    CONSTRAINT ck_notifications_entity CHECK (
        (related_entity_type IS NULL AND related_entity_id IS NULL)
        OR
        (related_entity_type IN (
            'SUBMISSION', 'VERIFICATION', 'JOB', 'APPLICATION', 'ASSIGNMENT', 'REPORT', 'ACCOUNT'
        ) AND related_entity_id IS NOT NULL AND related_entity_id > 0)
    ),
    CONSTRAINT ck_notifications_plain_text CHECK (
        title !~ '[<>]' AND message !~ '[<>]'
    )
);

