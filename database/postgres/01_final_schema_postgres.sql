-- PREMIUM_PAYMENTS records every checkout attempt. It is created before the
-- gateway is contacted, and only verified settlement marks it SUCCEEDED.
CREATE TABLE premium_payments (
    payment_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id              UUID DEFAULT gen_random_uuid() NOT NULL,
    user_id                BIGINT NOT NULL,
    plan_id                BIGINT NOT NULL,
    promo_code_id          BIGINT,
    base_amount_bdt        NUMERIC(10,2) NOT NULL,
    discount_amount_bdt    NUMERIC(10,2) DEFAULT 0 NOT NULL,
    final_amount_bdt       NUMERIC(10,2) NOT NULL,
    currency               VARCHAR(3) DEFAULT 'BDT' NOT NULL,
    gateway                VARCHAR(30) DEFAULT 'SSLCOMMERZ' NOT NULL,
    gateway_session_key    VARCHAR(255),
    gateway_transaction_id VARCHAR(255),
    gateway_validation_id  VARCHAR(255),
    status                 VARCHAR(10) DEFAULT 'INITIATED' NOT NULL,
    initiated_at           TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at           TIMESTAMPTZ,
    created_at             TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at             TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_premium_payments PRIMARY KEY (payment_id),
    CONSTRAINT uk_premium_payments_public UNIQUE (public_id),
    CONSTRAINT fk_premium_payment_user FOREIGN KEY (user_id)
        REFERENCES users (user_id),
    CONSTRAINT fk_premium_payment_plan FOREIGN KEY (plan_id)
        REFERENCES premium_plans (plan_id),
    CONSTRAINT fk_premium_payment_promo FOREIGN KEY (promo_code_id)
        REFERENCES premium_promo_codes (promo_code_id),
    CONSTRAINT ck_premium_payment_amounts CHECK (
        base_amount_bdt >= 0 AND discount_amount_bdt >= 0 AND final_amount_bdt >= 0
        AND final_amount_bdt = base_amount_bdt - discount_amount_bdt
    ),
    CONSTRAINT ck_premium_payment_currency CHECK (currency = 'BDT'),
    CONSTRAINT ck_premium_payment_status CHECK (
        status IN ('INITIATED', 'PENDING', 'SUCCEEDED', 'FAILED', 'CANCELLED', 'REFUNDED')
    ),
    CONSTRAINT ck_premium_payment_completion CHECK (
        (status IN ('INITIATED', 'PENDING') AND completed_at IS NULL)
        OR (status NOT IN ('INITIATED', 'PENDING') AND completed_at IS NOT NULL)
    )
);

