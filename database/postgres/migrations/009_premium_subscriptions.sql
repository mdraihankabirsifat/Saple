-- Existing vacancies stay FREE; only a representative or the optional demo
-- script ever marks a job PREMIUM.
ALTER TABLE job_postings
    ADD COLUMN IF NOT EXISTS access_level VARCHAR(10) DEFAULT 'FREE' NOT NULL
    CONSTRAINT ck_job_access_level CHECK (access_level IN ('FREE', 'PREMIUM'));

CREATE INDEX IF NOT EXISTS ix_job_postings_access ON job_postings (access_level);

-- Two new notification types for the trial and for a purchase.
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS ck_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type CHECK (notification_type IN (
    'VERIFICATION_DECISION',
    'SUBMISSION_DECISION',
    'REPRESENTATIVE_DECISION',
    'REPORT_OUTCOME',
    'APPLICATION_RECEIVED',
    'APPLICATION_STATUS',
    'JOB_CLOSED',
    'SECURITY_EVENT',
    'PREMIUM_TRIAL_STARTED',
    'PREMIUM_PURCHASE'
));

-- The public jobs view carries access_level so the API can show a locked
-- teaser for Premium vacancies. New column appended at the end.
CREATE OR REPLACE VIEW vw_public_open_jobs AS
SELECT jp.job_id,
       jp.company_id,
       c.company_name,
       c.industry,
       jp.role_id,
       jr.role_name,
       jr.role_category,
       jp.title,
       jp.description,
       jp.requirements,
       jp.location,
       jp.employment_type,
       jp.work_mode,
       jp.salary_min,
       jp.salary_max,
       jp.salary_currency,
       jp.salary_period,
       jp.application_deadline,
       jp.published_at,
       jp.access_level
FROM job_postings jp
JOIN companies c ON c.company_id = jp.company_id
LEFT JOIN job_roles jr ON jr.role_id = jp.role_id
WHERE jp.job_status = 'PUBLISHED'
  AND jp.application_deadline >= CURRENT_DATE;

-- Supabase browser roles get no direct access to the new tables either.
DO $saple_security$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
    END IF;
END
$saple_security$;

COMMIT;
